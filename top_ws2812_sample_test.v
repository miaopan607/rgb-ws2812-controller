//==============================================================================
// 模块名称: top_ws2812_sample_test
// 功能说明: WS2812 快速驱动刷新速度板级测试。
// 设计说明:
//   1. 不使用 UART 输入，仅保留端口以匹配顶层引脚。
//   2. led_brightness 保持固定，只周期性切换 RGB 颜色数据。
//   3. 若实际灯带全绿/全灭切换明显变快，说明 ws2812_fast 刷新链路正常。
//==============================================================================
module top_ws2812_sample_test(
    input  clk,      // 50 MHz 系统时钟。
    input  rst_n,    // 异步低电平复位。
    input  uart_rx,  // 未使用的 UART 输入，仅用于保持工程端口一致。
    output led_out   // WS2812 串行数据输出。
);

//------------------------------------------------------------------------------
// 测试节拍参数。
//------------------------------------------------------------------------------
localparam integer CLK_HZ       = 50_000_000;                  // 系统时钟频率。
localparam integer CHANGE_MS    = 1;                           // 全亮/全灭切换周期，单位 ms。
localparam integer CHANGE_TICKS = (CLK_HZ / 1000) * CHANGE_MS; // 切换周期对应的时钟数。

//------------------------------------------------------------------------------
// 测试状态信号。
//------------------------------------------------------------------------------
reg [31:0] tick_cnt;    // 毫秒级切换计数器。
reg        led_enable;  // 测试使能: 1=全绿, 0=全灭。

wire unused_uart_rx = uart_rx; // 显式连接未使用输入，避免综合工具告警。
wire [23:0] test_rgb = led_enable ? 24'h00FF00 : 24'h000000; // 测试颜色: 全绿或全灭。
wire [191:0] test_rgb_data = {8{test_rgb}}; // 8 颗 LED 使用同一测试颜色。

//------------------------------------------------------------------------------
// 周期性切换全绿/全灭测试数据。
//------------------------------------------------------------------------------
always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        tick_cnt <= 32'd0;
        led_enable <= 1'b0;
    end else if (tick_cnt == CHANGE_TICKS - 1) begin
        tick_cnt <= 32'd0;
        led_enable <= ~led_enable;
    end else begin
        tick_cnt <= tick_cnt + 1'b1;
    end
end

//------------------------------------------------------------------------------
// WS2812 驱动实例。
//------------------------------------------------------------------------------
ws2812_fast u_ws2812_fast(
    .clk            (clk),
    .rst_n          (rst_n),
    .led_rgb_data   (test_rgb_data),
    .mode           (1'b1),
    .led_brightness ({8'h33, 8'h33}),
    .led_out        (led_out)
);

endmodule
